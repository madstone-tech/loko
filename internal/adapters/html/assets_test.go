// fontBudget is the cap on the bundled WOFF2 bytes (spec FR-031, SC-011).
const fontBudget = 500 * 1024

func TestFontBudget(t *testing.T) {
	t.Parallel()
	files, err := fs.Glob(builtinTheme, "theme/fonts/*.woff2")
	if err != nil || len(files) == 0 {
		t.Fatalf("no bundled fonts: %v", err)
	}
	total := 0
	for _, f := range files {
		data, err := fs.ReadFile(builtinTheme, f)
		if err != nil {
			t.Fatal(err)
		}
		total += len(data)
	}
	css := renderSite(t, loadProjection(t), nil)["assets/fonts.css"]
	t.Logf("fonts: %d files, %d KB of WOFF2, fonts.css %d KB", len(files), total/1024, len(css)/1024)
	if total > fontBudget {
		t.Errorf("bundled fonts are %d bytes, over the %d budget", total, fontBudget)
	}
}

var fontFaceSrc = regexp.MustCompile(`src: url\(data:font/woff2;base64,[A-Za-z0-9+/=]+\) format\("woff2"\);`)

// TestAssetsPublished: the fonts reach the site only through fonts.css, the
// licences only through LICENSES.txt, and each opens with the notice (014
// FR-020; feature 021, research R6).
func TestAssetsPublished(t *testing.T) {
	t.Parallel()
	out := renderSite(t, loadProjection(t), nil)

	fonts, _ := fs.Glob(builtinTheme, "theme/fonts/*.woff2")
	css := out["assets/fonts.css"]
	if n := strings.Count(css, "@font-face"); n != len(fonts) {
		t.Errorf("fonts.css has %d @font-face rules, want %d", n, len(fonts))
	}
	if n := len(fontFaceSrc.FindAllString(css, -1)); n != len(fonts) {
		t.Errorf("fonts.css has %d base64 WOFF2 sources, want %d", n, len(fonts))
	}

	eye := out["assets/brand/madstone-eye.svg"]
	if !strings.HasPrefix(eye, "<!-- Code generated by loko") || !strings.Contains(eye, "<svg") {
		t.Errorf("Eye glyph missing or without the notice: %.80q", eye)
	}

	licences := out["assets/LICENSES.txt"]
	ofl, _ := fs.Glob(builtinTheme, "theme/fonts/OFL-*.txt")
	for _, f := range append(ofl, "theme/brand/NOTICE.txt") {
		body, err := fs.ReadFile(builtinTheme, f)
		if err != nil {
			t.Fatal(err)
		}
		if !strings.Contains(licences, "== "+strings.TrimPrefix(f, "theme/")+" ==\n"+string(body)) {
			t.Errorf("LICENSES.txt lacks %s verbatim under its heading", f)
		}
	}

	for p := range out {
		if ext := path.Ext(p); ext == ".woff2" || strings.Contains(p, "OFL-") || strings.HasSuffix(p, "NOTICE.txt") {
			t.Errorf("%s is published on its own; it belongs in fonts.css or LICENSES.txt", p)
		}
	}
}

// cssRule matches one innermost rule: its selector list and its body.
var cssRule = regexp.MustCompile(`([^{}]+)\{([^{}]*)\}`)

var cssComment = regexp.MustCompile(`(?s)/\*.*?\*/`)

// fontOf returns the font-family value of the first rule whose selector list
// holds sel and that sets a font, and false when no rule sets one.
func fontOf(css, sel string) (string, bool) {
	for _, m := range cssRule.FindAllStringSubmatch(cssComment.ReplaceAllString(css, ""), -1) {
		for s := range strings.SplitSeq(m[1], ",") {
			if strings.TrimSpace(s) != sel {
				continue
			}
			for decl := range strings.SplitSeq(m[2], ";") {
				if k, v, ok := strings.Cut(decl, ":"); ok && strings.TrimSpace(k) == "font-family" {
					return strings.TrimSpace(v), true
				}
			}
		}
	}
	return "", false
}

// TestInterfaceFontToken: the interface text has its own font token, so a
// theme changes it in one place, and code keeps the mono font (contract T-1).
func TestInterfaceFontToken(t *testing.T) {
	t.Parallel()
	data, err := fs.ReadFile(builtinTheme, "theme/style.css")
	if err != nil {
		t.Fatal(err)
	}
	css := string(data)
	i := strings.Index(css, ":root {")
	if i < 0 {
		t.Fatal("style.css has no :root block")
	}
	root := css[i : i+strings.Index(css[i:], "}")]
	if !strings.Contains(root, `--font-ui: "JetBrains Mono", ui-monospace, monospace;`) {
		t.Errorf("the first :root block does not declare --font-ui with the 1.5 mono value")
	}
	if f, _ := fontOf(css, "code"); f != "var(--font-mono)" {
		t.Errorf("code, kbd, pre font = %q, want var(--font-mono)", f)
	}
	for _, sel := range []string{"th", ".sidebar", ".nav-section h2", ".search-input", ".breadcrumb ol",
		".kind-label", ".meta", ".pager-dir", ".theme-toggle", ".row-kind", ".row-tags", ".dir", ".chip",
		".stat-label", "figcaption"} {
		if f, ok := fontOf(css, sel); !ok || f != "var(--font-ui)" {
			t.Errorf("%s font = %q, want var(--font-ui)", sel, f)
		}
	}
}
