// fakeSVG stands in for a rendered view with a card per address.
func fakeSVG(addresses ...string) []byte {
	var b strings.Builder
	b.WriteString(`<?xml version="1.0" encoding="utf-8"?><!-- Code generated by loko. DO NOT EDIT. --><svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 50">`)
	for _, a := range addresses {
		b.WriteString(`<g class="x kind-component" data-loko-address="` + a + `"><rect/></g>`)
	}
	b.WriteString(`</svg>`)
	return []byte(b.String())
}

// renderWith renders the site with the views' SVGs available, as the staged
// build provides them (research R1).
func renderWith(t *testing.T, proj *vm.Projection, formats ...vm.Format) map[string]string {
	t.Helper()
	upstream := map[string][]byte{}
	for _, v := range proj.Views {
		var addrs []string
		for _, n := range v.Nodes {
			if n.Address != "" && (n.Role == vm.RoleElement || n.Role == vm.RoleInstance) {
				addrs = append(addrs, n.Address)
			}
		}
		upstream[v.DiagramPath] = fakeSVG(addrs...)
	}
	as, err := New().Render(context.Background(), proj, usecases.RenderOptions{Upstream: func() (map[string][]byte, error) { return upstream, nil }, Formats: formats})
	if err != nil {
		t.Fatal(err)
	}
	out := map[string]string{}
	for _, a := range as {
		out[a.Path] = string(a.Bytes)
	}
	return out
}

var railSection = regexp.MustCompile(`<section class="rail-card ([a-z-]+)"`)

// TestElementPage is User Story 1 (contracts/site-output.md § Element page).
func TestElementPage(t *testing.T) {
	t.Parallel()
	site := renderWith(t, loadProjection(t))
	repo := site["element/component/repo.html"]

	for _, want := range []string{
		`<p class="kind-label">COMPONENT · IN API</p>`,
		`<span class="icon-tile kind-component" aria-hidden="true"><i class="icon" data-icon="blocks"></i></span><span class="title">repo</span></h1>`,
		`<span>component.repo</span>`,
		`<span>main.loko.hcl:`,
	} {
		if !strings.Contains(repo, want) {
			t.Errorf("repo header lacks %q", want)
		}
	}
	rail := repo[strings.Index(repo, `<aside class="rail"`):]
	var order []string
	for _, m := range railSection.FindAllStringSubmatch(rail, -1) {
		order = append(order, m[1])
	}
	if strings.Join(order, " ") != "part-of siblings talks-to in-context" {
		t.Errorf("rail sections = %v, want part-of siblings talks-to in-context", order)
	}
	if n := strings.Count(repo, "<svg role=\"img\""); n != 1 {
		t.Errorf("%d inline SVGs, want exactly one", n)
	}
	if n := strings.Count(repo, "loko-focus"); n != 1 || !strings.Contains(repo, `loko-focus" data-loko-address="component.repo"`) {
		t.Errorf("focus marks %d groups; want only component.repo", n)
	}
	if !strings.Contains(repo, `<li class="row current" aria-current="true">`) {
		t.Error("siblings do not mark the current element")
	}

	// A page without prose moves In context into the main column.
	for path, body := range site {
		if !strings.HasPrefix(path, "element/") || strings.Contains(body, `<section class="markdown-content">`) {
			continue
		}
		main := body[strings.Index(body, `<div class="element-main">`):strings.Index(body, `<aside class="rail"`)]
		if strings.Contains(body, `class="rail-card in-context"`) && !strings.Contains(main, "in-context") {
			t.Errorf("%s has no prose but keeps In context in the rail", path)
		}
	}

	api := site["element/container/api.html"]
	if !strings.Contains(api, `<section class="children" aria-labelledby="children-h">`) ||
		!strings.Contains(api, `<img src="../../diagrams/container-api.svg"`) {
		t.Error("a container page lists its children and shows its own view as an image")
	}
}

// TestTalksToOneRowPerNeighbour is spec FR-013 and SC-003.
func TestTalksToOneRowPerNeighbour(t *testing.T) {
	t.Parallel()
	proj := loadProjection(t)
	site := renderWith(t, proj)
	for _, p := range proj.Pages {
		body := site[p.PagePath]
		i := strings.Index(body, `<ul class="rows neighbours">`)
		if i < 0 {
			continue
		}
		list := body[i : i+strings.Index(body[i:], "</ul>")]
		seen := map[string]bool{}
		for _, m := range regexp.MustCompile(`<li class="row">.*?<a href="([^"]+)"`).FindAllStringSubmatch(list, -1) {
			if seen[m[1]] {
				t.Errorf("%s: %s listed twice in Talks to", p.PagePath, m[1])
			}
			seen[m[1]] = true
		}
		if len(seen) != len(p.Neighbours) {
			t.Errorf("%s: %d Talks to rows, want %d", p.PagePath, len(seen), len(p.Neighbours))
		}
	}
}

func TestProseInheritedPage(t *testing.T) {
	t.Parallel()
	proj := loadProjection(t)
	for i := range proj.Pages {
		if proj.Pages[i].Address == "component.repo" {
			proj.Pages[i].ProseInherited = true
		}
	}
	repo := renderWith(t, proj)["element/component/repo.html"]
	if !strings.Contains(repo, `<p class="prose-inherited">This element is documented with its parent, <a href="../../element/container/api.html">`) {
		t.Error("an inherited page links to its parent's prose")
	}
	if strings.Contains(repo, `<section class="markdown-content">`) {
		t.Error("an inherited page must not repeat the parent's prose (FR-009)")
	}
}
