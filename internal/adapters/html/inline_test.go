const sampleSVG = `<?xml version="1.0" encoding="utf-8"?><!-- Code generated by loko from a.loko.hcl. DO NOT EDIT. -->` +
	`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 10 10"><svg class="d2-1 d2-svg" viewBox="0 0 10 10">` +
	`<g class="YQ== kind-container" data-loko-address="container.a"><rect/></g>` +
	`<g class="Yg== kind-container" data-loko-address="container.b"><rect/></g></svg></svg>`

func TestInlineSVG(t *testing.T) {
	t.Parallel()
	got := string(inlineSVG([]byte(sampleSVG), "cap", "desc", "container.b"))
	if strings.Contains(got, "<?xml") || strings.Contains(got, "Code generated") {
		t.Errorf("prolog or notice kept: %.120s", got)
	}
	if !strings.HasPrefix(got, `<svg role="img" aria-labelledby="cap" aria-describedby="desc" xmlns=`) {
		t.Errorf("root attributes: %.120s", got)
	}
	if strings.Count(got, `role="img"`) != 1 {
		t.Error("only the outer <svg> gets the accessibility attributes")
	}
	if n := strings.Count(got, "loko-focus"); n != 1 ||
		!strings.Contains(got, `<g class="Yg== kind-container loko-focus" data-loko-address="container.b">`) {
		t.Errorf("focus marking (%d): %s", n, got)
	}

	plain := string(inlineSVG([]byte(sampleSVG), "cap", "", "container.zzz"))
	if strings.Contains(plain, "loko-focus") || strings.Contains(plain, "aria-describedby") {
		t.Errorf("unknown focus or no description changed the groups: %s", plain)
	}
	if strings.Replace(plain, `<svg role="img" aria-labelledby="cap" `, "<svg ", 1) != sampleSVG[strings.Index(sampleSVG, "<svg"):] {
		t.Errorf("apart from the root attributes the SVG must be unchanged:\n%s", plain)
	}
	if inlineSVG(nil, "cap", "", "") != "" {
		t.Error("no SVG gives no markup")
	}
}

// TestFillInline: a page renders with a placeholder while the SVGs are still
// rendering; the placeholder becomes the diagram, or an image of it when the
// SVG is missing, and an upstream failure fails the render (research R1).
func TestFillInline(t *testing.T) {
	t.Parallel()
	proj := loadProjection(t)
	as, err := New().Render(context.Background(), proj, usecases.RenderOptions{
		Upstream: func() (map[string][]byte, error) { return map[string][]byte{}, nil }})
	if err != nil {
		t.Fatal(err)
	}
	for _, a := range as {
		if strings.Contains(string(a.Bytes), string(inlinePlaceholder)) {
			t.Errorf("%s keeps the placeholder", a.Path)
		}
		if a.Path == "element/component/repo.html" &&
			!strings.Contains(string(a.Bytes), `<div class="diagram-panel"><img src="../../diagrams/container-api.svg" alt="api diagram">`) {
			t.Error("a missing SVG must fall back to an image of the diagram")
		}
	}
	_, err = New().Render(context.Background(), proj, usecases.RenderOptions{
		Upstream: func() (map[string][]byte, error) { return nil, errors.New("svg failed") }})
	if err == nil || !strings.Contains(err.Error(), "svg failed") {
		t.Errorf("an upstream failure must fail the render, got %v", err)
	}
}
