// TestThemeDefaultsLight is spec FR-024 (research R5): light on a bare
// :root, dark only from the system preference (unless the reader chose light)
// or the toggle, and both dark blocks agree.
func TestThemeDefaultsLight(t *testing.T) {
	t.Parallel()
	light, dark, css := themeTokens(t)
	if light["--bg"] != "#F9FAFB" || dark["--bg"] != "#0F1117" {
		t.Errorf("surfaces: light %s, dark %s", light["--bg"], dark["--bg"])
	}
	i := strings.Index(css, "@media (prefers-color-scheme: dark) {\n  :root:not([data-theme=\"light\"]) {")
	if i < 0 {
		t.Fatal("no system-preference dark block guarded by data-theme=light")
	}
	media := map[string]string{}
	body := css[i : i+strings.Index(css[i:], "\n  }")]
	for _, m := range tokenDecl.FindAllStringSubmatch(body, -1) {
		media[m[1]] = strings.ToUpper(m[2])
	}
	for k, v := range media {
		if dark[k] != v {
			t.Errorf("%s is %s under the media query but %s under data-theme=dark", k, v, dark[k])
		}
	}
	if len(media) == 0 {
		t.Error("the media-query block defines no tokens")
	}
}

// TestNoNetworkReferences is spec FR-031 and SC-007: nothing is fetched from
// the network; the footer's "Generated by loko" link is an ordinary anchor.
func TestNoNetworkReferences(t *testing.T) {
	t.Parallel()
	footer := `<a href="https://github.com/madstone-tech/loko">loko</a>`
	network := regexp.MustCompile(`(?i)(https?:|url\(\s*["']?//|(src|href)="//)`)
	for path, body := range renderWith(t, loadProjection(t)) {
		body = strings.ReplaceAll(body, footer, "")
		body = strings.ReplaceAll(body, `xmlns="http://www.w3.org/2000/svg"`, "")
		body = strings.ReplaceAll(body, `xmlns:xlink="http://www.w3.org/1999/xlink"`, "")
		if strings.HasSuffix(path, ".txt") {
			continue // licence texts cite their URLs; nothing loads them
		}
		if m := network.FindString(body); m != "" {
			i := strings.Index(body, m)
			t.Errorf("%s references the network: %q", path, body[max(0, i-40):min(len(body), i+60)])
		}
	}
}

// TestHeadThemeScript: the pre-paint script is small, survives blocked
// storage, and only sets data-theme to a known value.
func TestHeadThemeScript(t *testing.T) {
	t.Parallel()
	index := renderSite(t, loadProjection(t), nil)["index.html"]
	m := regexp.MustCompile(`<script>(.*?)</script>`).FindStringSubmatch(index)
	if m == nil {
		t.Fatal("no inline head script")
	}
	script := m[1]
	if len(script) >= 400 || !strings.Contains(script, `localStorage.getItem("loko-theme")`) ||
		!strings.HasPrefix(script, "try{") || !strings.Contains(script, "document.documentElement.dataset.theme") {
		t.Errorf("head script: %s", script)
	}
	if strings.Index(index, "<script>") > strings.Index(index, `assets/style.css`) {
		t.Error("the theme script must run before the stylesheet loads, to avoid a flash")
	}
}

// TestFontStacksFallBack is SC-011: every font stack ends in a generic
// family, so characters outside the Latin subset still render.
func TestFontStacksFallBack(t *testing.T) {
	t.Parallel()
	_, _, css := themeTokens(t)
	stacks := regexp.MustCompile(`(--font-[a-z]+):\s*([^;]+);`).FindAllStringSubmatch(css, -1)
	if len(stacks) < 4 {
		t.Fatalf("found %d font stacks, want at least 4", len(stacks))
	}
	for _, s := range stacks {
		parts := strings.Split(s[2], ",")
		last := strings.TrimSpace(parts[len(parts)-1])
		switch last {
		case "system-ui", "sans-serif", "ui-monospace", "monospace", "serif":
		default:
			t.Errorf("%s ends in %q, not a generic family", s[1], last)
		}
	}
}
